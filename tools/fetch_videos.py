#!/usr/bin/env python3
"""
Pull the Karis YouTube channel feed and prepare it for the Watch page.

Writes `src/data/videos.json` and downloads each video's thumbnail into
`assets/img/videos/`, so the page can show the whole library without making a
single request to YouTube until a visitor actually presses play.

Run whenever new videos are published:

    python3 tools/fetch_videos.py
    python3 tools/build.py
"""
from __future__ import annotations

import html
import json
import re
import sys
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "src" / "data"
THUMBS = ROOT / "assets" / "img" / "videos"

CHANNEL_ID = "UCmTF1aNoSBiDqbbOEAsH8DQ"          # @isharethatyoumayknow
FEED = f"https://www.youtube.com/feeds/videos.xml?channel_id={CHANNEL_ID}"
UA = {"User-Agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)"}

ENTRY = re.compile(
    r"<entry>.*?<yt:videoId>(?P<id>.*?)</yt:videoId>"
    r".*?<title>(?P<title>.*?)</title>"
    r".*?<published>(?P<published>.*?)</published>"
    r"(?:.*?<media:description>(?P<description>.*?)</media:description>)?",
    re.S,
)

MONTHS = ("January February March April May June July "
          "August September October November December").split()


def get(url: str) -> bytes:
    return urllib.request.urlopen(
        urllib.request.Request(url, headers=UA), timeout=30).read()


def pretty_date(iso: str) -> str:
    y, m, d = iso[:10].split("-")
    return f"{int(d)} {MONTHS[int(m) - 1]} {y}"


def first_sentences(text: str, limit: int = 190) -> str:
    """Trim a YouTube description down to a usable card blurb."""
    text = html.unescape(text or "").strip()
    # Drop hashtag piles, bare URLs and social-follow boilerplate.
    text = re.sub(r"https?://\S+", "", text)
    text = re.sub(r"#\w+", "", text)
    # The site's copy carries no em dashes, so strip them out of imported
    # descriptions too: a full stop already ends the clause, otherwise comma.
    text = re.sub(r"([.!?])\s*[—–]\s*", r"\1 ", text)
    text = re.sub(r"\s*—\s*", ", ", text)
    text = re.sub(r"\s+", " ", text).strip(" -–|·")
    if not text:
        return ""
    if len(text) <= limit:
        return text
    cut = text[:limit]
    stop = max(cut.rfind(". "), cut.rfind("! "), cut.rfind("? "))
    return (cut[:stop + 1] if stop > 80 else cut.rsplit(" ", 1)[0] + "…").strip()


def save_thumb(video_id: str) -> str | None:
    """Grab the best available thumbnail and store it locally as a JPEG."""
    THUMBS.mkdir(parents=True, exist_ok=True)
    dest = THUMBS / f"{video_id}.jpg"
    tmp = THUMBS / f"{video_id}.tmp"

    for name in ("maxresdefault", "sddefault", "hqdefault"):
        try:
            data = get(f"https://i.ytimg.com/vi/{video_id}/{name}.jpg")
        except Exception:
            continue
        # YouTube serves a 120x90 grey placeholder when a size is unavailable.
        if len(data) < 6000:
            continue
        tmp.write_bytes(data)
        try:
            im = Image.open(tmp).convert("RGB")
            if im.width < 480:
                tmp.unlink(missing_ok=True)
                continue
            if im.width > 960:
                im = im.resize((960, round(im.height * 960 / im.width)), Image.LANCZOS)
            im.save(dest, "JPEG", quality=82, optimize=True, progressive=True)
            tmp.unlink(missing_ok=True)
            print(f"  {dest.relative_to(ROOT)}  {im.width}x{im.height}  "
                  f"{dest.stat().st_size / 1024:.0f}KB")
            return f"assets/img/videos/{video_id}.jpg"
        except Exception:
            tmp.unlink(missing_ok=True)
            continue

    print(f"  ! no usable thumbnail for {video_id}")
    return None


def main() -> int:
    print(f"\nFetching {FEED}")
    try:
        xml = get(FEED).decode("utf-8", errors="replace")
    except Exception as exc:
        print(f"error: could not read the channel feed: {exc}", file=sys.stderr)
        return 1

    channel = re.search(r"<title>(.*?)</title>", xml)
    channel_name = html.unescape(channel.group(1)) if channel else "I Share That You May Know"

    videos = []
    for m in ENTRY.finditer(xml):
        vid = m.group("id")
        videos.append({
            "id": vid,
            "title": html.unescape(m.group("title")).strip(),
            "published": m.group("published")[:10],
            "published_label": pretty_date(m.group("published")),
            "description": first_sentences(m.group("description")),
            "thumbnail": save_thumb(vid),
        })

    if not videos:
        print("error: the feed contained no videos", file=sys.stderr)
        return 1

    DATA.mkdir(parents=True, exist_ok=True)
    (DATA / "videos.json").write_text(json.dumps({
        "_comment": ("Generated by tools/fetch_videos.py from the channel's public "
                     "RSS feed. Re-run it after publishing a video, then run "
                     "tools/build.py. Safe to edit titles and descriptions by hand; "
                     "re-running overwrites them."),
        "channel_name": channel_name,
        "channel_url": "https://youtube.com/@isharethatyoumayknow",
        "channel_id": CHANNEL_ID,
        "videos": videos,
    }, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"\n{len(videos)} videos written to src/data/videos.json\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
